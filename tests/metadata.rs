mod support;
use support::Case;

#[test]
fn metadata_identifies_the_compiler_and_source_comments_preserve_loaded_inputs() {
    let source = "include \"extra.rusk\";\ninclude \"extra.rusk\";\n// */ trailing backslash \\\nwt compiler_version(),compiler_source_url(),value;\n";
    let extra = "let value := 42;\r\n// extra */ \\\r\n";
    let case = Case::new(source);
    std::fs::write(case.0.join("extra.rusk"), extra).unwrap();
    let out = case.run("");
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert_eq!(
        String::from_utf8(out.stdout).unwrap(),
        format!(
            "{} {} 42\n",
            env!("CARGO_PKG_VERSION"),
            env!("CARGO_PKG_REPOSITORY")
        )
    );
    let cpp = std::fs::read_to_string(case.0.join("main.cpp")).unwrap();
    assert!(cpp.starts_with(&format!(
        "// Generated by Rusk {}.",
        env!("CARGO_PKG_VERSION")
    )));
    let sources = cpp
        .lines()
        .filter_map(|line| line.strip_prefix("// Rusk source JSON: "))
        .map(|json| serde_json::from_str::<serde_json::Value>(json).unwrap())
        .collect::<Vec<_>>();
    assert_eq!(sources.len(), 2);
    assert_eq!(
        cpp.lines()
            .filter(|line| line.starts_with("// Rusk source: "))
            .count(),
        2
    );
    for (name, text) in [("main.rusk", source), ("extra.rusk", extra)] {
        let file = sources
            .iter()
            .find(|file| file["name"].as_str().unwrap().ends_with(name))
            .unwrap();
        assert_eq!(file["text"], text);
    }
    let compiled = case.compile();
    assert!(compiled.status.success());
    assert_eq!(
        std::fs::read_to_string(case.0.join("main.cpp")).unwrap(),
        cpp
    );
}

#[test]
fn revision_availability_and_modified_state_are_consistent() {
    let case = Case::new("wt compiler_revision().is_some()==compiler_modified().is_some();");
    let out = case.run("");
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert_eq!(out.stdout, b"Yes\n");
}
